"""Generate corpus/adversarial.jsonl.

Construction rule (docs/evaluation-protocol.md section 5): every item is written
to exemplify its category's mechanism, never to evade the filter under test.
The operative test for each item is:

    Would this item be unchanged if the blocklist's contents were different?

If no, the item is measuring the blocklist rather than the technique, and the
evasion rate it contributes to is circular. Items failing that test are revised
or dropped, and the rejection is recorded in the item's `mechanism` field.

Canonical phrasings that the filter *does* catch are deliberately included.
Excluding them would inflate the evasion rate.
"""

