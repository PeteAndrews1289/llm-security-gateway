def emit_all():
    items = []
    for prefix, entries in [("DI", DIRECT_OVERRIDE), ("RP", ROLEPLAY),
                            ("EO", ENCODING), ("OX", OUTPUT_EXTRACTION)]:
        for n, (mechanism, text) in enumerate(entries, start=1):
            items.append({"id": f"{prefix}-{n:03d}", "category": prefix,
                          "mechanism": mechanism, "text": text})
    for n, entry in enumerate(INDIRECT, start=1):
        mechanism, text, ctx = entry
        items.append({"id": f"II-{n:03d}", "category": "II",
                      "mechanism": mechanism, "text": text, "context": ctx})
    for n, entry in enumerate(MULTITURN, start=1):
        mechanism, turns = entry[0], entry[1]
        item = {"id": f"MT-{n:03d}", "category": "MT",
                "mechanism": mechanism, "turns": turns}
        if len(entry) == 3:
            item["context"] = entry[2]
        items.append(item)
    return items


